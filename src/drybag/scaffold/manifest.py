"""The machine ledger every whole-file template the engine writes is recorded in.

The manifest is committed, and it is the only reason `skip_modified` can exist: without a
recorded hash there is no way to tell a file the tool wrote from a file a person wrote, and every
refresh would be either a clobber or a no-op. It carries a `format` so a later migration can key
on it, and it is written atomically, because it is the one file whose corruption stops every
later plan over the tree it records (`drybag overlay upgrade`'s, for an overlay).

Its own path is repository-controlled too. `.drybag` is an ordinary directory entry that a
repository may commit as a symlink, and a clone materialises one, so both ends of the ledger
go through `contained()` first: otherwise `write` hands the records — content and all — to
whatever the link points at, and `read` takes its idea of what drybag owns from there.

`contained()` catches a *committed* symlink and not the race the engine exists to survive — a
component that becomes a link after the check passed. So the write goes through
`fsops.write_within`, the same `O_NOFOLLOW` walk every scaffolded artifact is written through.
It did not, and that was the gap worth naming: every file a user can shrug at was written
through a descriptor, while the one file whose corruption stops every later plan was written by
re-resolved string path — `mkdir(parents=True)` following symlinks
and `mkstemp` plus `os.replace` on the name. The strongest protection was applied to the least
valuable targets.
"""

from __future__ import annotations

import hashlib
import json
from dataclasses import asdict, dataclass
from enum import StrEnum
from pathlib import Path

from drybag import fsops
from drybag.config.paths import contained
from drybag.errors import Refusal
from drybag.fsops import UnsafePath, read_regular_text, write_within
from drybag.jsonobject import json_object

MANIFEST_PATH = Path(".drybag") / "manifest.json"
FORMAT = 1

GENERATED = "Generated by drybag; do not hand-edit."
# The one value a record's `kind` holds.
KIND = "template"


class ManifestError(Refusal):
    """A manifest that cannot be trusted: unreadable, malformed, or carrying unknown values."""


class Location(StrEnum):
    REPO = "repo"
    LOCAL = "local"


@dataclass(frozen=True)
class Record:
    """One artifact as the run that wrote it left it.

    `template` names the shipped file the bytes came from, `overlay/<name>`. Nothing reads it.
    """

    id: str
    kind: str
    location: Location
    target: str
    template: str
    version: str
    sha256: str


def digest(text: str) -> str:
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


def _record_from(raw: object, key: str) -> Record:
    if not isinstance(raw, dict):
        raise ManifestError(f"artifact {key!r} is not a table")
    try:
        if raw["kind"] != KIND:
            raise ValueError(f"{raw['kind']!r} is not a recorded kind")
        location = Location(raw["location"])
        return Record(
            id=str(raw["id"]),
            kind=KIND,
            location=location,
            target=str(raw["target"]),
            template=str(raw["template"]),
            version=str(raw["version"]),
            sha256=str(raw["sha256"]),
        )
    except ValueError as exc:
        raise ManifestError(f"artifact {key!r}: {exc}") from exc
    except KeyError as exc:
        raise ManifestError(f"artifact {key!r} is missing {exc.args[0]!r}") from exc


def _contained_path(root: Path) -> Path:
    """`root/.drybag/manifest.json`, refused when anything redirects it out of the root.

    The guard lives here rather than at each call site because this module owns
    `MANIFEST_PATH`: nothing else knows where the ledger lives, so nothing else can be asked
    to remember to check it. `read` consumes the returned path; `write` uses it only for the
    verdict, and then writes through the walk instead of through the string.
    """
    return contained(root, str(MANIFEST_PATH))


@dataclass(frozen=True)
class Manifest:
    records: dict[str, Record]
    format: int = FORMAT

    @classmethod
    def read(cls, root: Path) -> Manifest:
        path = _contained_path(root)
        if not fsops.is_file(path):
            return cls({})
        # The file is tracked, so a clone chooses every way it can fail to read: its size too, so
        # it is read to the read cap (`fsops.read_regular_text`), and a fault is said without the
        # path it was opened by. Bytes that are not UTF-8 fail in the decode, before the parser
        # runs. The parse goes through `jsonobject`, which answers JSON nested past the parser and
        # an integer longer than it converts in words of its own: quoting those exceptions told the
        # owner of a committed ledger to raise an interpreter limit, or reported the parser's
        # stack.
        with fsops.reading(MANIFEST_PATH, ManifestError):
            text = read_regular_text(path)
        raw = json_object(text, str(MANIFEST_PATH), error=ManifestError)
        version = raw.get("format", FORMAT)
        # Damage, not a newer drybag: `null`, `"1"`, `0` and the rest are no format any
        # drybag writes, and "upgrade the plugin" is the wrong remedy for them. `bool` is an
        # `int` to `isinstance`, and no format either.
        if not isinstance(version, int) or isinstance(version, bool) or version < 1:
            raise ManifestError(f"{MANIFEST_PATH}: 'format' is not a positive integer")
        if version > FORMAT:
            raise ManifestError(
                f"{MANIFEST_PATH} was written by a newer drybag (format {version!r}); "
                "upgrade the plugin rather than editing it"
            )
        artifacts = raw.get("artifacts", {})
        if not isinstance(artifacts, dict):
            raise ManifestError(f"{MANIFEST_PATH}: 'artifacts' is not an object")
        return cls({key: _record_from(value, key) for key, value in artifacts.items()}, version)

    def write(self, root: Path) -> Path:
        """Replace the ledger through the `O_NOFOLLOW` walk, and refuse rather than raise.

        `contained()` first, for the verdict a user can act on and for the committed-symlink
        case; `write_within` then, so no component of the path is resolved a second time
        between the two. An `OSError` here is a `ManifestError` — this file is written from
        `apply`'s `finally`, and a bare traceback out of that would take the report of what was
        already written with it.
        """
        path = _contained_path(root)
        body = {
            "_generated": GENERATED,
            "format": FORMAT,
            "artifacts": {key: asdict(self.records[key]) for key in sorted(self.records)},
        }
        try:
            write_within(root, str(MANIFEST_PATH), json.dumps(body, indent=2) + "\n")
        except UnsafePath as exc:
            raise ManifestError(f"{MANIFEST_PATH} cannot be written: {exc}") from exc
        except OSError as exc:
            raise ManifestError(f"{MANIFEST_PATH} cannot be written: {exc}") from exc
        return path

    def get(self, artifact_id: str) -> Record | None:
        return self.records.get(artifact_id)

    def with_record(self, record: Record) -> Manifest:
        return Manifest({**self.records, record.id: record}, self.format)
